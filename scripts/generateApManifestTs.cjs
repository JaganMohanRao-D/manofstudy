const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'public', 'AP_EAPCET_2025_ALLOTMENT_BY_COLLEGE');
const indexFile = path.join(dir, 'index.json');
const manifestFile = path.join(dir, 'manifest.json');

const indexData = JSON.parse(fs.readFileSync(indexFile, 'utf8'));
const manifestData = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));

// Enhance manifest with min/max rank per branch and per college
const collegesEnhanced = [];

indexData.colleges.forEach((col) => {
  const filePath = path.join(dir, col.file);
  const exists = fs.existsSync(filePath);

  if (exists) {
    try {
      const colData = JSON.parse(fs.readFileSync(filePath, 'utf8'));
      const branches = colData.branches || [];
      let totalRecords = 0;
      let colMinRank = Infinity;
      let colMaxRank = -Infinity;
      const branchSummaries = [];

      branches.forEach((b) => {
        const recs = b.records || [];
        totalRecords += recs.length;
        let bMin = Infinity;
        let bMax = -Infinity;
        const bPhases = new Set();
        const bCategories = new Set();

        recs.forEach((r) => {
          const num = parseFloat(r.rank);
          if (!isNaN(num) && num > 0) {
            if (num < bMin) bMin = num;
            if (num > bMax) bMax = num;
            if (num < colMinRank) colMinRank = num;
            if (num > colMaxRank) colMaxRank = num;
          }
          if (r.phase) bPhases.add(r.phase);
          if (r.category) bCategories.add(r.category);
        });

        branchSummaries.push({
          branchCode: b.branch_code,
          branchName: b.branch_name,
          recordCount: recs.length,
          minRank: bMin === Infinity ? 0 : Math.round(bMin),
          maxRank: bMax === -Infinity ? 0 : Math.round(bMax),
          phases: Array.from(bPhases).sort(),
          categories: Array.from(bCategories).sort()
        });
      });

      collegesEnhanced.push({
        collegeCode: col.college_code,
        collegeName: colData.college_name || col.college_name,
        file: col.file,
        hasData: true,
        recordCount: totalRecords,
        minRank: colMinRank === Infinity ? 0 : Math.round(colMinRank),
        maxRank: colMaxRank === -Infinity ? 0 : Math.round(colMaxRank),
        branchCount: branchSummaries.length,
        branches: branchSummaries
      });
    } catch (err) {
      console.error('Error with', col.file, err.message);
    }
  } else {
    collegesEnhanced.push({
      collegeCode: col.college_code,
      collegeName: col.college_name,
      file: col.file,
      hasData: false,
      recordCount: 0,
      minRank: 0,
      maxRank: 0,
      branchCount: 0,
      branches: []
    });
  }
});

const tsContent = `// AUTOGENERATED BUILD-TIME MANIFEST FROM public/AP_EAPCET_2025_ALLOTMENT_BY_COLLEGE/
// DO NOT EDIT MANUALLY. Run 'node scripts/generateApManifestTs.cjs' to regenerate.

export interface ApBranchItem {
  branchCode: string;
  branchName: string;
  recordCount: number;
  minRank: number;
  maxRank: number;
  phases: number[];
  categories: string[];
}

export interface ApCollegeItem {
  collegeCode: string;
  collegeName: string;
  file: string;
  hasData: boolean;
  recordCount: number;
  minRank: number;
  maxRank: number;
  branchCount: number;
  branches: ApBranchItem[];
}

export interface ApAllotmentGlobalStats {
  totalColleges: number;
  collegesWithData: number;
  totalBranches: number;
  totalRecords: number;
  categories: string[];
  allottedCategories: string[];
  regions: string[];
  phases: number[];
  minRank: number;
  maxRank: number;
  generatedAt: string;
}

export const AP_EAPCET_GLOBAL_STATS: ApAllotmentGlobalStats = ${JSON.stringify(
  {
    ...manifestData.stats,
    generatedAt: manifestData.generated_at
  },
  null,
  2
)};

export const AP_EAPCET_COLLEGES: ApCollegeItem[] = ${JSON.stringify(collegesEnhanced, null, 2)};
`;

fs.writeFileSync(path.join(__dirname, '..', 'src', 'data', 'apEapcetCollegeManifest.ts'), tsContent);
console.log('Successfully created src/data/apEapcetCollegeManifest.ts with', collegesEnhanced.length, 'colleges');
